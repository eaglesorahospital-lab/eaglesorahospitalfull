// 7. Operational Metrics Helper for Admin Dashboard
// -----------------------------------------------------------------------------
export function getAdminDashboardStats(appointments = INITIAL_DEMO_APPOINTMENTS, doctors = DEMO_DOCTORS, patients = INITIAL_DEMO_PATIENTS) {
  const totalDoctors = doctors.length;
  const activeDoctors = doctors.filter((d) => d.status !== 'Inactive').length;
  const totalDepartments = DEMO_DEPARTMENTS.length;
  const totalPatients = patients.length;

  const todayAppointments = appointments.filter((a) => a.date === '2026-11-09' || a.date === '2026-11-10');
  const pendingRequests = appointments.filter((a) => a.status === 'REQUESTED');
  const confirmedAppointments = appointments.filter((a) => a.status === 'CONFIRMED' || a.status === 'CHECKED_IN');
  const completedAppointments = appointments.filter((a) => a.status === 'COMPLETED');
  const cancelledAppointments = appointments.filter((a) => a.status === 'CANCELLED');

  return {
    totalDoctors,
    activeDoctors,
    totalDepartments,
    totalPatients,
    todayAppointmentsCount: todayAppointments.length,
    pendingRequestsCount: pendingRequests.length,
    confirmedAppointmentsCount: confirmedAppointments.length,
    completedAppointmentsCount: completedAppointments.length,
    cancelledAppointmentsCount: cancelledAppointments.length,
  };
}
